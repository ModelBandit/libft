void	*ft_memchr(const void *s, int c, unsigned int n)
{
	char			*sp;
	unsigned int	i;

	sp = (char *)s;
	i = 0;
	while (i < n)
	{
		if (sp[i] == c)
			return (&(sp[i]));
		++i;
	}
	return (sp);
}
