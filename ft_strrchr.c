char	*ft_strrchr(const char *s, int c)
{
	char	*sp;
	char	*rp;

	sp = (char *)s;
	rp = 0;
	while (*sp != '\0')
	{
		if (*sp == c)
			rp = sp;
		++sp;
	}
	return (rp);
}
