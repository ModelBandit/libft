void	*ft_memset(void *s, int c, int n)
{
	unsigned char	uc;
	char			*cs;
	int				i;

	uc = (unsigned char)c;
	cs = (char *)s;
	i = 0;
	while (i < n)
	{
		*cs = uc;
		++cs;
		++i;
	}
}
